namespace {
constexpr double relative_fraction_tolerance = 1e-14;
constexpr double absolute_fraction_tolerance = 1e-15;
const double infinity = std::numeric_limits<double>::infinity();
const double quiet_nan = std::numeric_limits<double>::quiet_NaN();

void check_fraction(double actual, double expected) {
    if (std::isnan(expected)) {
        CHECK(std::isnan(actual));
    } else if (std::isinf(expected)) {
        CHECK(actual == expected);
    } else if (expected == 0.0) {
        CHECK(actual == expected);
        CHECK(std::signbit(actual) == std::signbit(expected));
    } else {
        CHECK(std::abs(actual - expected) <= absolute_fraction_tolerance + std::abs(expected) * relative_fraction_tolerance);
    }
}
} // namespace

