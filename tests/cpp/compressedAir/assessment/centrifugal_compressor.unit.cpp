    CHECK(resLul.airflowAcfm == Approx(753.84478));
    CHECK(resLul.powerFraction == Approx(0.36));
    CHECK(resLul.airflowFraction == Approx(0.24023));
    resLul = cclUL.calculateFromMeasuredCapacity(753.12);
