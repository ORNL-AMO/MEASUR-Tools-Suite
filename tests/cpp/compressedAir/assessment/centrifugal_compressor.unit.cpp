    CHECK(resLul.airflowFraction == Approx(0.24));
    resLul = cclUL.calculateFromMeasuredPower(162.828);
    CHECK(resLul.powerKw == Approx(162.828));
    CHECK(resLul.airflowAcfm == Approx(753.8448));
