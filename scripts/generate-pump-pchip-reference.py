#!/usr/bin/env python3
"""Generate independent native/browser goldens with SciPy 1.17.1 (not a runtime dependency)."""
import json
import math
from pathlib import Path

import scipy
from scipy.interpolate import PchipInterpolator

if scipy.__version__ != '1.17.1':
    raise RuntimeError('Reference generation requires scipy==1.17.1')

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / 'tests/fixtures/pump_efficiency_hi_2020_data.json').read_text())
STYLES = {'A': 0, 'B': 1, 'C': 3, 'D': 2, 'E': 5, 'F': 6, 'G': 10, 'H': 4, 'J': 8, 'V': 9}


def curve(kind, key):
    x, y = zip(*DATA[kind][key]['points'])
    return PchipInterpolator(x, y, extrapolate=False)


def samples(kind):
    results = []
    for key, table in DATA[kind].items():
        if key == 'Negative':
            continue
        xs = [p[0] for p in table['points']]
        queries = set(xs)
        for low, high in zip(xs, xs[1:]):
            queries.update(low + t * (high - low) for t in [0.25, 0.5, 0.75])
        queries.update(e['x'] for e in DATA['examples'] if e['kind'] == kind and e['category'] == key)
        style = STYLES[key] if kind == 'base' else (9 if key == 'V' else 6)
        interpolator = curve(kind, key)
        for x in sorted(queries):
            y = float(interpolator(x))
            if kind == 'correction':
                y /= 100
            if kind == 'deviation':
                y = 1 + y / 100
            results.append([style, x, y])
    return results


def composite(style, rpm, viscosity, stages, flow, head):
    key = next(k for k, v in STYLES.items() if v == (9 if style == 7 else style))
    speed = rpm * math.sqrt(flow) / (head / stages) ** 0.75
    base = float(curve('base', key)(flow))
    correction = float(curve('correction', 'V' if style == 9 else 'All but V')(speed)) / 100
    parameter = 26.6 * (viscosity ** 0.5 * head ** 0.0625) / (flow ** 0.375 * rpm ** 0.25)
    viscosity_factor = min(1, parameter ** (-(0.0547 * parameter ** 0.69)))
    average = base / 100 * viscosity_factor - correction
    maximum = average * (1 + float(curve('deviation', 'Positive')(flow)) / 100)
    return [style, rpm, viscosity, stages, flow, head, average, maximum]


reference = {'scipyVersion': scipy.__version__, 'extrapolate': False,
             'base': samples('base'), 'correction': samples('correction'), 'deviation': samples('deviation')}
reference['composite'] = [composite(6, 2000, 1.107, 1, 2000, 137)]
for style in range(11):
    key = next(k for k, v in STYLES.items() if v == (9 if style == 7 else style))
    points = DATA['base'][key]['points']
    flow = (points[0][0] + points[-1][0]) / 2
    for stages, viscosity in [(1, 1.107), (1.5, 100), (3, 1000)]:
        # Exercise both sides of the correction minimum, including a nonzero correction.
        speed = 6000 if style == 9 else 1500
        rpm = speed * (137 / stages) ** 0.75 / math.sqrt(flow)
        reference['composite'].append(composite(style, rpm, viscosity, stages, flow, 137))

utility_tables = [([0, 1], [2, 5]), ([0, 1, 3, 7], [0, 2, 2, 1]),
                  ([0, 2, 3, 8], [0, 0.2, 5, 6]), ([0, 1, 2], [0, 4, 3]),
                  ([35, 100, 1000, 10000], [-8, -6.5, -3.7, -2])]
reference['interpolation'] = []
for xs, ys in utility_tables:
    interpolator = PchipInterpolator(xs, ys, extrapolate=False)
    queries = sorted(set(xs + [a + (b - a) * t for a, b in zip(xs, xs[1:]) for t in [0.1, 0.5, 0.9]]))
    reference['interpolation'].append({'x': xs, 'y': ys, 'samples': [[x, float(interpolator(x))] for x in queries]})

fixture = ROOT / 'tests/fixtures/pump_efficiency_hi_2020_reference'
fixture.with_suffix('.json').write_text(json.dumps(reference, indent=2, allow_nan=False) + '\n')
lines = ['// Generated by scripts/generate-pump-pchip-reference.py using SciPy ' + scipy.__version__,
         '#pragma once', '#include <array>', 'namespace hi2020_reference {']
for key in ['base', 'correction', 'deviation', 'composite']:
    size = len(reference[key][0])
    lines.append('inline constexpr double ' + key + '[][' + str(size) + '] = {')
    lines.extend('    {' + ', '.join(repr(x) for x in row) + '},' for row in reference[key])
    lines.append('};')
for i, table in enumerate(reference['interpolation']):
    for key in ['x', 'y']:
        lines.append('inline constexpr double utility' + str(i) + '_' + key + '[] = {' + ', '.join(repr(x) for x in table[key]) + '};')
    lines.append('inline constexpr double utility' + str(i) + '_samples[][2] = {')
    lines.extend('    {' + ', '.join(repr(x) for x in row) + '},' for row in table['samples'])
    lines.append('};')
lines.append('} // namespace hi2020_reference')
fixture.with_suffix('.h').write_text('\n'.join(lines) + '\n')
browser = ROOT / 'tests/wasm-mocha/motorDriven/pump/hi_2020_reference.ts'
browser.write_text('// Generated SciPy ' + scipy.__version__ + ' goldens; extrapolate=False.\nexport const reference = ' + json.dumps(reference, indent=2, allow_nan=False) + ';\n')
print('Generated', {k: len(reference[k]) for k in ['base', 'correction', 'deviation', 'composite']})
